// Builds qa/system-inventory.md from the code itself (routes, endpoints, schema).
// Run: node qa/tools/inventory.mjs   (from the repo root)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const be = path.join(root, 'src/backend');
const fe = path.join(root, 'src/frontend/src');
const read = (p) => fs.readFileSync(p, 'utf8');

// ── Backend: mount prefixes from app.js, endpoints from each router file ──
const app = read(path.join(be, 'src/app.js'));
const imports = {};
for (const m of app.matchAll(/import\s+(?:(\w+)|\{([^}]+)\})\s+from\s+'(\.\/routes\/[^']+)'/g)) {
  const names = m[1] ? [m[1]] : m[2].split(',').map((s) => s.trim().split(/\s+as\s+/).pop());
  for (const n of names) imports[n] = path.join(be, 'src', m[3]);
}
const mounts = [];
for (const m of app.matchAll(/app\.use\('([^']+)',\s*(?:[\w.]+\s*,\s*)*(\w+)\)/g)) mounts.push({ prefix: m[1], name: m[2], file: imports[m[2]] });

const endpoints = [];
const seen = new Set();
for (const { prefix, name, file } of mounts) {
  if (!file || !fs.existsSync(file)) continue;
  const src = read(file);
  // Named routers (portal.js exports two): pick lines for this router variable when present.
  const varName = new RegExp(`\\b${name}\\.(get|post|put|patch|delete)\\('([^']*)'`, 'g');
  const generic = /\brouter\.(get|post|put|patch|delete)\('([^']*)'/g;
  const re = src.match(varName) ? varName : generic;
  for (const r of src.matchAll(re)) {
    const ep = `${r[1].toUpperCase()} ${(prefix + (r[2] === '/' ? '' : r[2])).replace(/\/+$/, '') || '/'}`;
    if (seen.has(ep)) continue; seen.add(ep);
    endpoints.push({ ep, file: path.relative(root, file) });
  }
}

// ── Schema ──
const schema = read(path.join(be, 'prisma/schema.prisma'));
const models = [...schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)].map((m) => ({
  name: m[1],
  fields: m[2].split('\n').filter((l) => /^\s+\w+\s+\S/.test(l) && !/^\s+@@/.test(l)).length,
  fks: (m[2].match(/@relation\([^)]*fields:/g) || []).length,
  status: /\bstatus\s+(\w+)/.exec(m[2])?.[1] || null,
}));
const enums = Object.fromEntries([...schema.matchAll(/^enum (\w+) \{([\s\S]*?)^\}/gm)].map((m) => [m[1], m[2].split('\n').map((s) => s.trim()).filter((s) => s && !s.startsWith('//'))]));

// ── Frontend routes ──
const router = read(path.join(fe, 'router/AppRouter.jsx'));
const routes = [...new Set([...router.matchAll(/path: '([^']+)'/g)].map((m) => m[1]))];
const services = fs.readdirSync(path.join(fe, 'services')).filter((f) => f.endsWith('.js'));
const mockServices = services.filter((f) => /\bMOCK_|mockData|faker|setTimeout\(\s*resolve/.test(read(path.join(fe, 'services', f))));

// ── Write ──
const byArea = {};
for (const e of endpoints) { const a = e.ep.split(' ')[1].split('/').slice(0, 4).join('/'); (byArea[a] ||= []).push(e); }
const lines = [];
lines.push('# System inventory', '', `Generated by \`qa/tools/inventory.mjs\` from the code on ${new Date().toISOString().slice(0, 10)}. Re-run it after changes.`, '');
lines.push('## Totals', '', '| Item | Count |', '|---|---:|',
  `| API mounts (app.js) | ${mounts.length} |`, `| API endpoints | ${endpoints.length} |`,
  `| Frontend routes | ${routes.length} |`, `| Frontend service files | ${services.length} |`,
  `| Service files that still look mock-backed | ${mockServices.length} |`,
  `| Database models | ${models.length} |`, `| Enums | ${Object.keys(enums).length} |`, '');
if (mockServices.length) lines.push('Mock-looking services: ' + mockServices.map((s) => '`' + s + '`').join(', '), '');
lines.push('## Status enums (state machines)', '');
for (const [n, v] of Object.entries(enums).filter(([n]) => /Status|State|Stage/.test(n))) lines.push(`- **${n}**: ${v.join(' → ')}`);
lines.push('', '## Database models', '', '| Model | Fields | Foreign keys | Status field |', '|---|---:|---:|---|');
for (const m of models) lines.push(`| ${m.name} | ${m.fields} | ${m.fks} | ${m.status || ''} |`);
lines.push('', '## API endpoints by area', '');
for (const [a, eps] of Object.entries(byArea).sort()) {
  lines.push(`### ${a} (${eps.length})`, '', ...eps.map((e) => `- \`${e.ep}\` — ${e.file}`), '');
}
lines.push('## Frontend routes', '', ...routes.map((r) => `- \`${r}\``), '');
fs.writeFileSync(path.join(root, 'qa/system-inventory.md'), lines.join('\n'));
fs.writeFileSync(path.join(root, 'qa/.inventory.json'), JSON.stringify({ endpoints, models, enums, routes, mockServices }, null, 1));
console.log(`endpoints ${endpoints.length}, mounts ${mounts.length}, routes ${routes.length}, models ${models.length}, enums ${Object.keys(enums).length}, mock services ${mockServices.length}`);
