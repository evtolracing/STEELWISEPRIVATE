#!/usr/bin/env node
// Writes qa/role-matrix.md: for every role, the areas its menu offers, the branches it sees, whether
// it may change records, manage logins or preview other roles. Read from the code, never typed by
// hand: src/frontend/src/config/roleAccess.js (screens), src/backend/src/lib/roleAccess.js,
// lib/branchScope.js and lib/viewScope.js (server).
//   node qa/tools/role-matrix.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const load = (rel) => import(pathToFileURL(path.join(root, rel)));
const fe = await load('src/frontend/src/config/roleAccess.js');
const be = await load('src/backend/src/lib/roleAccess.js');
const { ALL_BRANCH_ROLES } = await load('src/backend/src/lib/branchScope.js');
const { SYSTEM_ADMIN_ROLES } = await load('src/backend/src/lib/viewScope.js');

const AREA = {
  sales: 'Sales', orders: 'Orders', billing: 'Invoices', production: 'Production', inventory: 'Stock', purchasing: 'Purchasing',
  opsCockpit: 'Ops cockpit', quality: 'Quality', materialTracking: 'Material tracking', logistics: 'Receiving and shipping',
  supplierQuality: 'Supplier quality', customerQuality: 'Customer quality', ecommerce: 'Web shop', ecommerceAdmin: 'Web shop settings',
  maintenance: 'Maintenance', contractors: 'Contractors', executive: 'Executive', finance: 'Finance', adminUsers: 'Users',
  adminStaff: 'Staff', adminRecipes: 'Processing recipes', adminIntegrations: 'Partner API and integrations', admin: 'System settings',
};
const sample = Object.fromEntries(Object.entries(fe.SECTION_PATHS).map(([k, v]) => [k, `/${v[0]}`]));
const USER_MANAGERS = new Set(['SUPER_ADMIN', 'TENANT_OWNER', 'ADMIN', 'BRANCH_MANAGER']); // routes/users.js POST and PUT
const changes = (role) => {
  const g = be.staffGroupOf(role);
  if (['SUPPLIER_USER', 'CARRIER_USER'].includes(role)) return 'Through the partner API only';
  if (be.EXTERNAL_ROLES.has(role)) return 'Own account in the web shop';
  if (g === 'readOnly') return 'Nothing (view-only)';
  if (SYSTEM_ADMIN_ROLES.has(role)) return 'Everything';
  if (g === 'admin' || g === 'leadership') return 'Any working record they can see';
  if (!g) return 'Nothing listed';
  return `${g[0].toUpperCase()}${g.slice(1)} records`;
};

const rows = fe.ALL_ROLES.map((role) => {
  const areas = Object.keys(AREA).filter((a) => fe.canAccessPath(role, sample[a])).map((a) => AREA[a]);
  const branches = be.EXTERNAL_ROLES.has(role) ? 'Own account' : ALL_BRANCH_ROLES.has(role) ? 'Every branch' : 'Own branches';
  return `| ${role} | ${areas.length === Object.keys(AREA).length ? 'Everything' : areas.join(', ') || (fe.isExternalRole(role) ? 'Help only' : 'Dashboards, safety, training and help only')} | ${branches} | ${changes(role)} | ${USER_MANAGERS.has(role) ? (role === 'BRANCH_MANAGER' ? 'Own branch staff' : 'Yes') : 'No'} | ${SYSTEM_ADMIN_ROLES.has(role) ? 'Yes' : 'No'} |`;
});

const out = [
  '# Role and permission matrix', '',
  'Generated by `qa/tools/role-matrix.mjs` from the code. Do not edit by hand: change the code and rerun.', '',
  'Every column is enforced on the server; the menu only mirrors it. "Menu" is the areas a role\'s menu offers and the pages it may open; dashboards, safety, training and help are open to all staff. "Branches" is what the server sends: a login held to its own branches sees its home branch plus any assigned to it. "Changes" is the department write rule (`src/backend/src/lib/roleAccess.js`). "Users" is who may add and change logins (`routes/users.js`, `lib/userAdminRules.js`). "Preview" is the View as picker (`lib/viewScope.js`): view-only, never above the person\'s own role.', '',
  'The branch picker in the top bar narrows any login to one of the branches in its "Branches" column. It can never widen them.', '',
  '| Role | Menu | Branches | Changes | Users | Preview |', '|---|---|---|---|---|---|', ...rows, '',
];
fs.writeFileSync(path.join(root, 'qa/role-matrix.md'), out.join('\n'));
console.log(`qa/role-matrix.md: ${rows.length} roles`);
